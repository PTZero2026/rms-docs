import { choose } from "../../lib/choice.mjs"
import { expect, test } from "@playwright/test"
import { readFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import { catalogUser } from "./fixtures"
import { provision } from "../../integration/session-fixture"

test("B01 admin previews a detected PNG, reads XML in its stored charset and downloads the original bytes", async ({ page }) => {
  test.skip(process.env.RMS_OIDC_INTEGRATION !== "1")
  const admin = await catalogUser(page, "school-2", "quan-tri-dinh-dang", "admin")
  const png = await readFile(new URL("./sample-3k.png", import.meta.url))
  const key = "B01.DINH-DANG"
  const get = () => page.request.get(admin.path + "/" + key, { headers: admin.headers })
  await page.getByRole("button", { name: "Cấu hình hệ thống" }).click()
  await page.getByRole("button", { name: "Thêm cấu hình" }).click()
  await page.getByLabel("Mã cấu hình").fill(key)
  await choose(page.getByLabel("Cách nhập"), "file")
  await page.getByLabel("Tệp nội dung").setInputFiles({ name: "mau.bin", mimeType: "application/octet-stream", buffer: png })
  await page.getByRole("button", { name: "Xem trước", exact: true }).click()
  await expect(page.getByText(/Xem trước · image\/png · .+ · 3072 byte/)).toBeVisible()
  expect((await get()).status()).toBe(404)
  const saving = page.waitForResponse(r => r.request().method() === "POST" && new URL(r.url()).pathname === admin.path)
  await page.getByRole("button", { name: "Lưu cấu hình" }).click()
  const saved = await (await saving).json()
  await expect(page.getByText("Đã lưu cấu hình.")).toBeVisible()
  const stored = await get()
  expect(stored.headers()["content-type"]).toBe("image/png")
  expect(await stored.body()).toEqual(png)
  const image = page.getByRole("img", { name: key, exact: true })
  await expect(image).toBeVisible()
  await expect.poll(() => image.evaluate(node => (node as HTMLImageElement).naturalWidth)).toBe(32)
  const localDay = new Intl.DateTimeFormat("sv-SE", {
    timeZone: "Asia/Ho_Chi_Minh", day: "2-digit", month: "2-digit", year: "numeric",
  }).format(new Date(saved.created))
  await page.getByText("Bộ lọc cấu hình", { exact: true }).click()
  await page.getByLabel("Từ khóa").fill(key)
  await page.getByLabel("Tạo từ").fill(localDay)
  await page.getByLabel("Tạo đến").fill(localDay)
  await page.getByRole("button", { name: "Tìm cấu hình" }).click()
  await expect(page.getByText("1 bản cấu hình", { exact: true })).toBeVisible()
  const xml = "<donvi>Khoa Thủy văn &amp; Tài nguyên nước</donvi>"
  const original = Buffer.from(xml, "utf16le")
  const row = page.getByRole("row").filter({ has: page.getByRole("cell", { name: key, exact: true }) })
  await row.getByRole("button", { name: "Sửa", exact: true }).click()
  await choose(page.getByLabel("Cách nhập"), "base64")
  await page.getByLabel("Loại nội dung", { exact: true }).fill("application/xml")
  await page.getByLabel("Bảng mã").fill("utf-16le")
  await page.getByLabel("Nội dung", { exact: true }).fill(original.toString("base64"))
  const xmlSaved = page.waitForResponse(r => r.request().method() === "PUT" && new URL(r.url()).pathname === admin.path + "/" + key)
  await page.getByRole("button", { name: "Lưu cấu hình" }).click()
  expect(await (await xmlSaved).json()).toMatchObject({mime:"application/xml",encoding:"utf-16le"})
  const xmlContent = await get()
  expect(xmlContent.headers()["content-type"]).toContain("charset=utf-16le")
  expect(await xmlContent.body()).toEqual(original)
  await expect(page.locator("pre")).toHaveText(xml)
  await expect(image).toHaveCount(0)
  const link = page.getByRole("link", { name: "Tải nội dung" })
  const downloaded = page.waitForEvent("download")
  await link.click()
  expect(await readFile((await (await downloaded).path())!)).toEqual(original)
  const detail = page.getByRole("region", { name: "Nội dung cấu hình" })
  await detail.screenshot({ path: fileURLToPath(new URL("../../../docs/reviews/screenshots/catalog/van-ban-theo-bang-ma.png", import.meta.url)) })
  await row.getByRole("button", { name: "Sửa", exact: true }).click()
  const edited = "<donvi>Phòng Quản lý khoa học</donvi>"
  await page.getByLabel("Nội dung", { exact: true }).fill(edited)
  await page.getByLabel("Bảng mã").fill("us-ascii")
  await page.getByRole("button", { name: "Lưu cấu hình" }).click()
  await expect(page.getByText("Bảng mã đã chọn không biểu diễn đủ ký tự trong nội dung.")).toBeVisible()
  expect(await (await get()).body()).toEqual(original)
  await page.getByLabel("Bảng mã").fill("utf-16le")
  await page.getByRole("button", { name: "Lưu cấu hình" }).click()
  await expect(detail.locator("pre")).toHaveText(edited)
  expect(await (await get()).body()).toEqual(Buffer.from(edited, "utf16le"))

  const read = row.getByRole("button", { name: "Đọc hiệu lực" })
  async function replace(mime: string, encoding: string, bytes: Buffer) {
    const response = await page.request.put(admin.path + "/" + key, { headers: admin.headers,
      data: { mime_type: mime, encoding, content: bytes.toString("base64") } })
    expect(response.status()).toBe(200)
    await read.click()
  }
  const prefix = "a".repeat(65535)
  await replace("text/plain", "utf-8", Buffer.from(prefix + "ệ."))
  await expect(detail.getByText(/64 KiB/)).toBeVisible()
  expect(await detail.locator("pre").textContent()).toBe(prefix)
  await replace("text/plain", "unknown-charset", Buffer.from("Văn bản"))
  await expect(detail.getByText(/chưa đọc được văn bản/)).toBeVisible()
  await expect(link).toBeVisible()
  await replace("application/octet-stream", "utf-8", Buffer.from([0, 1, 2]))
  await expect(detail).toBeVisible()
  await expect(detail.locator("pre, img")).toHaveCount(0)
  await replace("application/xml", "utf-16le", original)
  await expect(page.locator("pre")).toHaveText(xml)

  await row.getByRole("button", { name: "Sửa", exact: true }).click()
  await page.getByLabel("Mô tả", { exact: true }).fill("Thay đổi chưa được duyệt")
  provision("UPDATE rms.account SET user_type='user' WHERE id=:'id'::uuid", { id:admin.account.id })
  await page.getByRole("button", { name: "Lưu cấu hình" }).click()
  await expect(page.getByText("Tài khoản thiếu quyền thực hiện.")).toBeVisible()
  await expect(detail).toHaveCount(0)
  await expect(page.getByLabel("Mô tả", { exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "Tải lại danh sách" }).click()
  await expect(row.getByRole("button", { name: "Sửa", exact: true })).toHaveCount(0)
  await read.click()
  await expect(page.locator("pre")).toHaveText(xml)

  provision("UPDATE rms.account SET is_active=false WHERE id=:'id'::uuid", { id:admin.account.id })
  await read.click()
  await expect(page.getByText("Tài khoản thiếu quyền thực hiện.")).toBeVisible()
  await expect(link).toHaveCount(0)
  await expect(page.getByText(xml, { exact: true })).toHaveCount(0)
})
