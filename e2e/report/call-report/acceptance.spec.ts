import { choose } from "../../lib/choice.mjs"
import { execFileSync } from "node:child_process"
import { fileURLToPath } from "node:url"
import { readFile } from "node:fs/promises"
import { expect,test } from "@playwright/test"
import { signIn,provision } from "../../integration/session-fixture"

test("head and unit officer reconcile frozen report, CSV and live roles",async({browser})=>{
  test.skip(process.env.RMS_OIDC_INTEGRATION!=="1")
  test.setTimeout(100000)
  const contexts=await Promise.all([0,1,2,3,4].map(()=>browser.newContext({baseURL:"http://127.0.0.1:4191"})))
  const pages=await Promise.all(contexts.map(context=>context.newPage()))
  const [lead,officer,pi,,other]=pages
  try{
    const actors=await Promise.all(pages.map((p,i)=>signIn(p,i===4?"school-2":"school-1",["truong-phong","can-bo-khoa","chu-nhiem-A","chu-nhiem-B","nguoi-truong-khac"][i].toLowerCase()+"-bc@example.invalid")))
    const {call,returned,a,b}=JSON.parse(execFileSync(process.execPath,[fileURLToPath(new URL("../../../apps/backend/test/db/seed-report-case.mjs",import.meta.url)),...actors.slice(0,4).map(a=>a.account.id)],{encoding:"utf8"}))
    for(const p of [lead,officer]){
      await p.getByRole("button",{name:"Tải lại thông tin"}).click()
      if(p===lead){
        const counters=p.getByRole("region",{name:"Số liệu nhanh"})
        await counters.getByText("Mở báo cáo theo kỳ",{exact:true}).click()
        await expect(p.getByLabel("Đơn vị báo cáo")).toHaveAttribute("data-value", a)
        await expect(p).toHaveURL(/\?report=home$/)
        await p.reload()
        await expect(p.getByLabel("Đơn vị báo cáo")).toHaveAttribute("data-value", a)
        await choose(p.getByLabel("Kỳ báo cáo"), call)
        const unitSnapshot=p.waitForResponse(r=>r.url().endsWith("/reports/calls/snapshots")&&r.request().method()==="POST")
        await p.getByRole("button",{name:"Tạo bản chụp"}).click()
        const scoped=await (await unitSnapshot).json()
        expect(scoped.rows.map((row:{unitId:string})=>row.unitId)).toEqual([a,a])
        await expect(p.getByText(/Tổng cộng 2 hồ sơ/)).toBeVisible()
        await p.reload()
        await expect(p.getByText(scoped.id,{exact:true})).toBeVisible()
        await expect(p.getByLabel("Đơn vị báo cáo")).toHaveAttribute("data-value", a)
        await p.getByRole("region",{name:"Báo cáo tiếp nhận"}).screenshot({path:fileURLToPath(new URL("../../../docs/reviews/screenshots/report/tu-trang-chu-pham-vi-khoa.png",import.meta.url))})
        await choose(p.getByLabel("Đơn vị báo cáo"), "")
      }else{
        await p.getByRole("button",{name:"Báo cáo theo kỳ"}).click()
        await expect(p.getByLabel("Đơn vị báo cáo")).toHaveAttribute("data-value", "")
        await choose(p.getByLabel("Kỳ báo cáo"), call)
      }
    }
    const response=lead.waitForResponse(r=>r.url().endsWith("/reports/calls/snapshots"))
    await lead.getByRole("button",{name:"Tạo bản chụp"}).click()
    const snapshot=await (await response).json()
    await expect(lead.getByText(/Trích xuất .*giờ Việt Nam/)).toContainText(/\b\d{2}\/\d{2}\/\d{4}\b/)
    expect(snapshot.total).toBe(3);expect(snapshot.groups).toEqual({SUBMITTED:2,DRAFT:1})
    const headers=async(i:number)=>({authorization:(await actors[i].res.request().allHeaders()).authorization})
    const result=await pi.request.post("/api/tenants/school-1/projects/"+returned.id+"/proposal/actions",{headers:await headers(2),data:{action:"submit",revision:returned.revision}})
    expect(result.status()).toBe(200)
    await lead.getByRole("radio",{name:"Nháp (1)"}).click()
    const draftLink=lead.getByRole("list",{name:"Mã đối chứng"}).getByRole("link",{name:"A2",exact:true})
    await draftLink.click()
    await expect(lead.getByRole("heading",{name:"Lịch sử hồ sơ"})).toBeVisible()
    await expect(lead.getByRole("heading",{name:"A2",exact:true})).toBeVisible()
    await lead.goBack()
    await expect(draftLink).toBeVisible()
    await lead.reload()
    await expect(draftLink).toBeVisible()
    await expect(lead.getByRole("radio",{name:"Nháp (1)"})).toBeChecked()
    await expect(lead.getByRole("list",{name:"Mã đối chứng"}).getByRole("listitem")).toHaveCount(1)
    await expect(lead.getByLabel("Kỳ báo cáo")).toHaveAttribute("data-value", call)
    await expect(lead.getByLabel("Đơn vị báo cáo")).toHaveAttribute("data-value", "")
    await expect(lead.getByText(snapshot.id,{exact:true})).toBeVisible()
    const oldLink=lead.url()
    await lead.getByRole("radio",{name:"Tất cả mã đã cấp"}).click()
    await expect(lead.getByRole("list",{name:"Mã đối chứng"}).getByRole("listitem")).toHaveCount(3)
    const download=lead.waitForEvent("download")
    await lead.getByRole("button",{name:"Xuất CSV đối chứng"}).click()
    const file=await download
    expect(file.suggestedFilename()).toContain(snapshot.id)
    const csv=await readFile((await file.path())!,"utf8")
    expect(csv).toContain(snapshot.capturedAt);expect(csv).toMatch(/"A2","Khoa Công trình","DRAFT"/);expect(csv).not.toContain('"A3"')
    expect(csv).toContain('"Mã bản chụp","'+snapshot.id+'"')
    expect(csv).toContain('"DRAFT","1"')
    expect(csv).toContain('"SUBMITTED","2"')
    expect(csv).toContain('"'+returned.id+'"')
    await file.saveAs(fileURLToPath(new URL("./doi-chieu-ky-mau.csv",import.meta.url)))
    await lead.getByRole("region",{name:"Báo cáo tiếp nhận"}).screenshot({path:fileURLToPath(new URL("../../../docs/reviews/screenshots/report/truong-phong-doi-chung.png",import.meta.url))})
    await lead.getByRole("button",{name:"Tạo bản chụp"}).click()
    await expect(lead.getByRole("radio",{name:"Đã nộp (3)"})).toBeVisible()
    await officer.getByRole("button",{name:"Tạo bản chụp"}).click()
    await expect(officer.getByText(/Tổng cộng 2 hồ sơ/)).toBeVisible()
    await officer.goto(oldLink)
    await expect(officer.getByRole("alert")).toContainText("Không thể mở bản chụp")
    await expect(officer.getByRole("list",{name:"Mã đối chứng"})).toHaveCount(0)
    expect((await officer.request.post("/api/tenants/school-1/reports/calls/snapshots",{headers:await headers(1),data:{callId:call,unitId:b}})).status()).toBe(403)
    provision("UPDATE rms.account SET user_type='staff' WHERE id=:'id'::uuid",{id:actors[4].account.id})
    expect((await other.request.get("/api/tenants/school-2/reports/calls/snapshots/"+snapshot.id,{headers:await headers(4)})).status()).toBe(404)
    const sourceTab=await lead.context().newPage()
    await sourceTab.goto(oldLink)
    await sourceTab.getByRole("link",{name:"A2",exact:true}).click()
    await expect(sourceTab.getByRole("heading",{name:"A2",exact:true})).toBeVisible()
    provision("DELETE FROM rms.report_unit_grant WHERE account_id=:'id'::uuid",{id:actors[0].account.id})
    await sourceTab.goBack()
    await expect(sourceTab.getByRole("alert")).toContainText("Phạm vi đã thay đổi")
    await expect(sourceTab.getByText(snapshot.id,{exact:true})).toHaveCount(0)
    await expect(sourceTab.getByRole("list",{name:"Mã đối chứng"})).toHaveCount(0)
    await sourceTab.getByRole("region",{name:"Báo cáo tiếp nhận"}).screenshot({
      path:fileURLToPath(new URL("../../../docs/reviews/screenshots/report/ban-chup-thu-hep-quyen.png",import.meta.url)),
    })
    await sourceTab.close()
    await lead.getByRole("button",{name:"Xuất CSV đối chứng"}).click()
    await expect(lead.getByRole("alert")).toHaveText(/Phạm vi|phạm vi/)
    await expect(lead.getByRole("radio",{name:"Tất cả mã đã cấp"})).toHaveCount(0)
    await lead.getByLabel("Đơn vị báo cáo").click()
    await expect(lead.getByRole("listbox").locator('[role="option"][data-value="'+b+'"]')).toHaveCount(0)
    await expect(lead.getByRole("listbox").locator('[role="option"][data-value="'+a+'"]')).toHaveCount(1)
    await lead.keyboard.press("Escape")
    await lead.goto(oldLink)
    await expect(lead.getByRole("alert")).toContainText("Phạm vi đã thay đổi")
    await expect(draftLink).toHaveCount(0)
    provision("UPDATE rms.account SET unit_id=NULL WHERE id=:'id'::uuid",{id:actors[0].account.id})
    await lead.goto("/app/school-1?report=home")
    await choose(lead.getByLabel("Kỳ báo cáo"), call)
    await expect(lead.getByLabel("Đơn vị báo cáo")).toHaveText("Chọn phạm vi báo cáo")
    await expect(lead.getByRole("button",{name:"Tạo bản chụp"})).toBeDisabled()
    await pi.goto("/app/school-1?report=home")
    await expect(pi.getByRole("alert")).toHaveText("Bạn chưa có quyền xem báo cáo kỳ.")
    await expect(pi.getByLabel("Kỳ báo cáo")).toHaveCount(0)
    await pi.getByRole("link",{name:"Về trang chủ"}).click()
    await expect(pi.getByRole("region",{name:"Trang chủ cá nhân"})).toBeVisible()
  }finally{await Promise.all(contexts.map(context=>context.close()))}
})
