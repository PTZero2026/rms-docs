import { choose } from "../../lib/choice.mjs"
import { randomUUID } from "node:crypto"
import { fileURLToPath } from "node:url"
import { expect,type Page } from "@playwright/test"
import { provision } from "../../integration/session-fixture"

export async function verifyAcceptance(officer:Page,pi:Page,member:Page,project:string,memberId:string,memberEmail:string,tenant:string,processOwner:string){
  const doi=randomUUID(),link="/app/school-1?project="+project
  provision(`INSERT INTO rms.intake_reference(tenant_id,id,kind,name,definition) VALUES(:'tenant',:'id','criteria','Thẩm định kết quả cuối kỳ',
    '{"type":"ACCEPTANCE","items":[{"key":"impact","label":"Chất lượng kết quả","weight":1,"maxScore":10}]}')`,{tenant,id:doi})
  const open=async(p:Page,name:string,region=name)=>{
    await p.goto(link)
    await p.getByRole("button",{name,exact:true}).click()
    return p.getByRole("region",{name:region,exact:true})
  }
  const funds=await open(officer,"Kinh phí đề tài","Sổ kinh phí")
  await funds.getByRole("button",{name:"Xác nhận cấp kinh phí",exact:true}).click()
  await expect(funds.getByText("Đã ghi nhận kinh phí.")).toBeVisible()
  const applicant=await open(pi,"Nghiệm thu đề tài")
  await expect(applicant.getByText("Kỳ cuối · Kỳ 1 · Đạt")).toBeVisible()
  await applicant.getByLabel("Tóm tắt hồ sơ cuối").fill("Hoàn thành số liệu, báo cáo cuối kỳ và bài báo theo cam kết.")
  await choose(applicant.getByLabel("Tệp hồ sơ cuối"), {label:"Bao-cao-ky-1.pdf"})
  await applicant.getByRole("button",{name:"Nộp hồ sơ nghiệm thu"}).click()
  await expect(applicant.getByText("Đã nộp hồ sơ nghiệm thu.")).toBeVisible()
  await officer.goto("/app/school-1")
  await officer.getByRole("region",{name:"Việc cần làm"}).getByRole("link",{name:/Điều phối nghiệm thu · Quan trắc/}).click()
  const office=officer.getByRole("region",{name:"Nghiệm thu đề tài",exact:true})
  await office.getByText("Lập hội đồng nghiệm thu",{exact:true}).click()
  await office.getByLabel("Tên hội đồng nghiệm thu").fill("Hội đồng nghiệm thu cuối kỳ")
  await choose(office.getByLabel("Vai trò nghiệm thu "+memberEmail), "SECRETARY")
  await office.getByRole("button",{name:"Lưu hội đồng nghiệm thu"}).click()
  await expect(office.getByText("Đã lập hội đồng.")).toBeVisible()
  await choose(office.getByLabel("Tiêu chí nghiệm thu"), doi)
  await office.getByRole("button",{name:"Mở đợt nghiệm thu"}).click()
  await office.getByRole("button",{name:"Chốt kết luận nghiệm thu"}).click()
  await expect(office.getByRole("alert")).toContainText("Còn thiếu 1 phiếu")
  await member.goto("/app/school-1")
  await member.getByRole("button",{name:"Phiếu nghiệm thu",exact:true}).click()
  const queue=member.getByRole("region",{name:"Phiếu nghiệm thu",exact:true})
  await queue.getByLabel(/Chất lượng kết quả/).fill("8")
  await queue.getByLabel("Nhận xét chuyên môn").fill("Đã đối chiếu hồ sơ cuối kỳ và sản phẩm.")
  await queue.getByRole("button",{name:"Lưu nháp phiếu"}).click()
  await expect(queue.getByText("Đã lưu nháp phiếu.")).toBeVisible()
  provision("UPDATE rms.account SET is_active=false WHERE id=:'memberId'",{memberId})
  const locked=member.waitForResponse(r=>r.request().method()==="PUT"&&r.url().endsWith("/sheet"))
  await queue.getByRole("button",{name:"Lưu nháp phiếu"}).click()
  expect((await locked).status()).toBe(403)
  await expect(queue.getByRole("article")).toHaveCount(0)
  await expect(queue.getByRole("alert")).toBeVisible()
  provision("UPDATE rms.account SET is_active=true WHERE id=:'memberId'",{memberId})
  await member.goto("/app/school-1")
  const work=member.getByRole("region",{name:"Việc cần làm"})
  const ballot=work.getByRole("link",{name:/Chấm nghiệm thu · Quan trắc/})
  await expect(ballot).toBeVisible()
  const shot=(name:string)=>fileURLToPath(new URL("../../../docs/reviews/screenshots/acceptance/"+name+".png",import.meta.url))
  await work.screenshot({path:shot("thanh-vien-viec-nghiem-thu")})
  await ballot.click()
  const sheet=member.getByRole("region",{name:"Xử lý công việc"}).getByRole("article")
  await expect(sheet.getByLabel(/Chất lượng kết quả/)).toHaveValue("8")
  await expect(sheet.getByLabel("Nhận xét chuyên môn")).toHaveValue("Đã đối chiếu hồ sơ cuối kỳ và sản phẩm.")
  const source=member.getByRole("region",{name:"Xử lý công việc"})
  provision("INSERT INTO rms.project_member VALUES(:'tenant',:'project',:'memberId',false)",{tenant,project,memberId})
  const refused=member.waitForResponse(r=>r.request().method()==="PUT"&&r.url().endsWith("/sheet"))
  await sheet.getByLabel(/Chất lượng kết quả/).fill("9")
  await sheet.getByRole("button",{name:"Lưu nháp phiếu"}).click()
  expect((await refused).status()).toBe(404)
  await expect(source.getByRole("article")).toHaveCount(0)
  await expect(source.getByRole("alert")).toBeVisible()
  await member.getByRole("link",{name:"Về danh sách việc"}).click()
  await expect(work.getByText("Hiện bạn không có việc cần làm.")).toBeVisible()
  provision("DELETE FROM rms.project_member WHERE tenant_id=:'tenant' AND project_id=:'project' AND account_id=:'memberId'",{tenant,project,memberId})
  await member.reload()
  await ballot.click()
  await expect(sheet.getByLabel(/Chất lượng kết quả/)).toHaveValue("8")
  await sheet.getByRole("button",{name:"Gửi phiếu chấm"}).click()
  await expect(sheet.getByText("Điểm phiếu đã gửi · 8")).toBeVisible()
  await sheet.screenshot({path:shot("thu-ky-phieu-nghiem-thu")})
  await member.getByRole("link",{name:"Về danh sách việc"}).click()
  await expect(work.getByText("Hiện bạn không có việc cần làm.")).toBeVisible()
  await expect(ballot).toHaveCount(0)
  await office.getByRole("button",{name:"Chốt kết luận nghiệm thu"}).click()
  await expect(office.getByText("Kết luận nghiệm thu · Đạt")).toBeVisible()
  await office.screenshot({path:shot("chuyen-vien-ket-luan")})
  const amendment=office.getByRole("region",{name:"Điều chỉnh kết luận"})
  await amendment.getByLabel("Lý do điều chỉnh kết luận").fill("Kiểm tra bổ sung biên bản nghiệm thu.")
  await amendment.getByRole("button",{name:"Mở lại vòng",exact:true}).click()
  await expect(office.getByRole("button",{name:"Chốt kết luận nghiệm thu"})).toBeVisible()
  await expect(amendment.getByText(/Kết luận trước · Đạt · 1 phiếu/)).toBeVisible()
  await office.getByRole("button",{name:"Chốt kết luận nghiệm thu"}).click()
  await expect(office.getByText("Kết luận nghiệm thu · Đạt")).toBeVisible()
  const close=await open(officer,"Kinh phí đề tài","Sổ kinh phí")
  await close.getByLabel("Đã rà soát thủ công").check()
  await close.getByRole("button",{name:"Quyết toán và đóng đề tài"}).click()
  await expect(close.getByText("Đã quyết toán và khóa sổ · Rà thủ công")).toBeVisible()
  const archived=await open(officer,"Nghiệm thu đề tài")
  await choose(archived.getByLabel("Chủ quy trình nhận yêu cầu"), {label:processOwner})
  await archived.getByLabel("Lý do điều chỉnh kết luận").fill("Đối chiếu biên bản sau khi khóa sổ.")
  await archived.getByRole("button",{name:"Gửi yêu cầu đính chính"}).click()
  await expect(archived.getByText(/Đã chuyển cho/)).toBeVisible()
  await archived.getByRole("region",{name:"Điều chỉnh kết luận"}).screenshot({path:shot("chuyen-dinh-chinh")})
}
