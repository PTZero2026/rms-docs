      await expect(progress.getByText("Đã đo xong ba điểm quan trắc và đối chiếu số liệu.",{exact:true})).toBeVisible()
      await progress.screenshot({path:fileURLToPath(new URL("../../../docs/reviews/screenshots/extension/tien-do-nhom-sinh-vien.png",import.meta.url))})
